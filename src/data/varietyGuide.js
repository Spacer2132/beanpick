const normalize = (text) => String(text || '').toLowerCase().replace(/[\s\-_·]/g, '');

// 긴 별칭부터 맞춰 지운다 — '핑크버번'이 '버번'으로 중복 집계되지 않게
const ALIASES = VARIETY_TIERS
  .flatMap(({ items }) => items.flatMap((item) => item.aliases.map((alias) => ({ id: item.id, alias: normalize(alias) }))))
  .sort((a, b) => b.alias.length - a.alias.length);

export function matchVarietyIds(...texts) {
  let rest = normalize(texts.filter(Boolean).join(' '));
  const ids = new Set();
  for (const { id, alias } of ALIASES) {
    if (rest.includes(alias)) {
      ids.add(id);
      rest = rest.split(alias).join('|');
    }
  }
  return [...ids];
}
